"""Approve & fix: the supplier reviews the detective's suggestions for missing transport order numbers.

Original messages are never modified. Every decision is appended to fix_log; the "after" state
(score preview, IT note) is computed from original + latest decision per delivery note.
"""
import re
from datetime import datetime, timezone

import pandas as pd
import streamlit as st

# matching findings that disappear once the ASN carries a valid TO number
FIXABLE = {"ASN_TO_MISSING", "ASN_TO_IMPLAUSIBLE", "ASN_NO_STATUS"}
LOG_COLS = ["user_email", "supplier_code", "message_key", "delivery_note", "suggestion_id", "date_window",
            "field_path", "old_value", "new_value", "confidence", "decision", "source"]



def current_user():
    try:
        return st.context.headers.get("X-Forwarded-Email") or "unknown"
    except Exception:
        return "unknown"


def latest_decisions(qlive, T, code):
    """Current decision per delivery note (latest log row; 'undone' means pending again)."""
    return qlive(f"""
        SELECT * FROM (
          SELECT *, row_number() OVER (PARTITION BY message_key ORDER BY ts DESC) AS rn
          FROM {T}.fix_log WHERE supplier_code = :code)
        WHERE rn = 1 AND decision <> 'undone' ORDER BY ts DESC, message_key""", code=code)


def _undo(log_fn, execute, T, row, label):
    """Button callback: runs before the redraw, so the undone row has already left the ✅ Done list."""
    log_fn(execute, T, [{**row, "user_email": current_user(), "decision": "undone"}])
    st.toast(f"Undone: {label} is open again")


def log(execute, T, rows):
    if not rows:
        return
    values, params = [], {}
    for i, r in enumerate(rows):
        values.append("(current_timestamp(), " + ", ".join(f":{c}_{i}" for c in LOG_COLS) + ")")
        params.update({f"{c}_{i}": "" if r.get(c) is None else str(r.get(c)) for c in LOG_COLS})
    execute(f"INSERT INTO {T}.fix_log (ts, {', '.join(LOG_COLS)}) VALUES {', '.join(values)}", params)


def matching_score(bad, n_messages, fixed_keys):
    """Matching score if the ASNs in fixed_keys carried their (approved) TO number."""
    if not n_messages:
        return 0.0
    still_bad = sum(1 for r in bad.itertuples()
                    if not (r.msg_type == "4987" and r.message_key in fixed_keys and set(r.rules) <= FIXABLE))
    return round(100 * max(0, n_messages - still_bad) / n_messages, 1)


def row_for_log(r, decision, new_value=None):
    return {
        "user_email": current_user(), "supplier_code": r["supplier_code"], "message_key": r["message_key"],
        "delivery_note": r["delivery_note"], "suggestion_id": r["suggestion_id"], "date_window": r["date_window"],
        "field_path": r["field_path"], "old_value": r["current_value"],
        "new_value": new_value if new_value is not None else (r["suggested_value"] if decision == "approved" else ""),
        "confidence": r["confidence"], "decision": decision, "source": r["source"],
    }


def it_note(q, T, code, me, dec):
    """One-page note for the supplier's IT / EDI team: what their system sends wrong and how to fix it at the source."""
    counts = q(f"""SELECT f.rule_id, r.problem, r.field_path, r.fix, f.severity, count(*) AS n
                   FROM {T}.findings f JOIN {T}.rules r USING (rule_id)
                   WHERE f.supplier_code = :c AND f.responsible = 'supplier' AND f.severity IN ('error', 'warning')
                   GROUP BY ALL ORDER BY n DESC""", c=code)
    wrong = q(f"""SELECT value, count(*) AS n FROM {T}.findings WHERE supplier_code = :c AND rule_id = 'ASN_TO_IMPLAUSIBLE'
                  GROUP BY 1 ORDER BY n DESC LIMIT 3""", c=code)
    n87 = int(me["n_4987"])
    miss = counts[counts["rule_id"].isin(["ASN_TO_MISSING", "ASN_TO_IMPLAUSIBLE"])]["n"].sum()
    ex = dec[dec["decision"] == "approved"].head(5)
    lines = [
        f"# Data quality note for the IT / EDI team of {me['display_name']}",
        f"_Supplier code {code} · generated by the VDA Data Quality Cockpit on {datetime.now(timezone.utc):%d %b %Y} · "
        f"based on {n87} delivery notes (VDA 4987) and {int(me['n_4933'])} transport orders (VDA 4933) sent to the plant._",
        "",
        "## 1. Main issue: the transport order number is missing in your delivery notes",
        f"- **{int(miss)} of {n87} delivery notes** ({100 * miss / max(n87, 1):.0f} %) arrive at the plant without a usable "
        "transport order number.",
        "- **Field:** VDA 4987 / EDIFACT DESADV, segment **RFF+AAO** (JSON: `/references/rff_AAO_transportOrderNumber/value`).",
        "- **Correct value:** the number of the transport order (VDA 4933 T1, `beginningOfMessage/documentIdentifier`) "
        "that the truck for this shipment was booked with.",
        "- **Why it matters:** without it, the plant cannot link the delivery note to the truck, so the truck has to stop at "
        "the gate for a manual check.",
        "- **Likely cause:** the despatch-advice mapping in your ERP / EDI converter does not copy the transport order "
        "number into RFF+AAO.",
    ]
    if not wrong.empty:
        lines.append("- Some notes carry a wrong value instead: " + ", ".join(f"`{v}` ({n}×)" for v, n in zip(wrong["value"], wrong["n"]))
                     + " — e.g. the plant code instead of the transport order number.")
    if not ex.empty:
        lines += ["", "Examples confirmed by your team in the cockpit:", "",
                  "| delivery note | correct transport order number |", "|---|---|"]
        lines += [f"| {r.delivery_note} | {r.new_value} |" for r in ex.itertuples()]
    # linkage problems that the carrier has to fix do not belong into the supplier's IT note
    other = counts[~counts["rule_id"].isin(["ASN_TO_MISSING", "ASN_TO_IMPLAUSIBLE", "ASN_NO_STATUS", "T1_NO_STATUS"])].head(5)
    if not other.empty:
        lines += ["", "## 2. Other issues found in your messages", ""]
        lines += [f"- **{r.problem}** ({r.n}×) – field `{r.field_path}`. Fix: {r.fix}" for r in other.itertuples()]
    lines += ["", "## Checklist",
              "- [ ] Map the transport order number (VDA 4933) into RFF+AAO of every despatch advice (VDA 4987).",
              "- [ ] Send a test message and check the delivery note shows up as *linked* in the cockpit.",
              "- [ ] Then re-check the remaining issues above."]
    return "\n".join(lines)


WINDOWS = {"Same or next day (recommended)": "next_day", "Same day only (strict)": "same_day"}
PAGE = 8          # yellow cards / done rows shown at once
REJECT_OPT, LATER_OPT = "❌ none of these", "⏳ decide later"
OWN_OPT = "✏️ type the right number"


def typed_value(key, label, placeholder, known, own_number, own_label):
    """Text box for a number the user types instead of a suggestion. Returns the value, or LATER_OPT when
    nothing usable was typed (an empty box is not saved)."""
    v = st.text_input(label, key=key, placeholder=placeholder).strip()
    if not v:
        return LATER_OPT
    if v == str(own_number or "").strip():
        st.error(f"That is the {own_label} itself, not the number we need here.")
        return LATER_OPT
    if v in known:
        st.caption("✅ We know this number from your messages.")
    else:
        st.caption("⚠️ We don't have this number in our data (it is only a sample). Please double-check; it will "
                   "still be saved.")
    return v


def typed_row(row):
    """Mark a log row whose value was typed by the user, not picked from the detective's suggestions."""
    return {**row, "confidence": "manual", "source": "typed by user"}


def readable(name):
    """'Fiktiver Lieferant 9411 GmbH' (anonymised) -> 'Carrier 9411'."""
    m = re.match(r"Fiktiver Lieferant (\d+)", name or "")
    return f"Carrier {m.group(1)}" if m else (name or "carrier ?")


def _qty(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def evidence(q, T, s_row, to_number):
    """Explain in plain words why this delivery note belongs to this transport booking; details on demand."""
    note = q(f"SELECT part_number, quantity FROM {T}.items_4987 WHERE source = :s", s=s_row["source"])
    order = q(f"SELECT part_number, quantity FROM {T}.items_4933 WHERE to_number = :t", t=to_number)
    head = q(f"""SELECT requested_shipment_date AS d, requested_shipment_time AS t, carrier_name, unloading_point
                 FROM {T}.msg_4933 WHERE to_number = :t LIMIT 1""", t=to_number)
    truck = q(f"""SELECT plate, count(*) AS n FROM {T}.msg_4945
                  WHERE supplier_code = :sup AND shipment_number = :dn AND to_number = :t GROUP BY 1""",
              sup=s_row["supplier_code"], dn=s_row["delivery_note"], t=to_number)
    agg = lambda df: df.assign(q=df["quantity"].map(_qty)).groupby("part_number")["q"].sum()
    a, b = agg(note), agg(order)
    same = sum(1 for p in a.index if p in b.index and abs(a[p] - b[p]) < 1e-6)
    other_qty = sum(1 for p in a.index if p in b.index and abs(a[p] - b[p]) >= 1e-6)
    n, extra = len(a), sum(1 for p in b.index if p not in a.index)
    dn = s_row["delivery_note"]

    story = [f"📄 **Your delivery note {dn}** – the packing list you sent on {s_row['despatch_date']} – lists "
             f"**{n} kind{'s' if n != 1 else ''} of parts**, but not which transport booking they travel with."]
    if head.empty:
        story.append(f"📦 Booking **{to_number}** is not among the bookings we received, so we cannot compare the parts.")
    else:
        h = head.iloc[0]
        if same == n and n:
            match = f"with **exactly the same {n} part{'s' if n != 1 else ''} and amounts**"
        elif same + other_qty == n and n:
            match = f"with **the same {n} parts** ({other_qty} with a different amount)"
        else:
            match = f"containing **{same + other_qty} of these {n} parts**"
        story.append(f"📦 **On {h['d']} you booked transport {to_number}** with {readable(h['carrier_name'])} "
                     f"(pick-up {str(h['t'])[:5]}), {match}."
                     + (f" The booking has {extra} more part{'s' if extra != 1 else ''} – one truck often carries "
                        "several delivery notes." if extra else ""))
    if not truck.empty:
        story.append(f"🚚 **The truck of that booking ({truck.iloc[0]['plate'] or 'plate unknown'}) also reported "
                     f"delivery note {dn}.**")
    strong = (same == n and n > 0) or not truck.empty
    story.append(f"➜ So this delivery note **{'almost certainly' if strong else 'probably'}** belongs to booking "
                 f"**{to_number}**.")
    st.markdown("  \n".join(story))

    if st.toggle("Show the parts side by side", key=f"parts::{s_row['message_key']}::{to_number}"):
        rows = []
        for p in sorted(set(a.index) | set(b.index), key=lambda p: (p not in a.index, p)):
            qa, qb = a.get(p), b.get(p)
            if qa is not None and qb is not None:
                mark = "✅ same part, same amount" if abs(qa - qb) < 1e-6 else "🟨 same part, other amount"
            elif qa is not None:
                mark = "❌ only on the delivery note"
            else:
                mark = "➖ only in the booking"
            rows.append({"part number": p, "on delivery note": qa, "in booking": qb, "": mark})
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True,
                     height=min(36 * (len(rows) + 1) + 4, 250))


def accuracy_note(q, T, window, conf):
    acc = q(f"SELECT verifiable, correct, accuracy_pct FROM {T}.detective_quality WHERE date_window = :w AND confidence = :c",
            w=window, c=conf)
    if acc.empty or not acc.iloc[0]["verifiable"]:
        return ""
    a = acc.iloc[0]
    return (f"Back-test: on {int(a['verifiable'])} delivery notes where a truck status tells us the true order, "
            f"this kind of suggestion was right **{int(a['correct'])} times ({a['accuracy_pct']:.0f}%)**.")


@st.fragment
def render(q, qlive, execute, T, code, me):
    """Runs as a fragment: saving decisions only refreshes this section, not the whole page."""
    # hide the whole section when this company has no suggestions and no decisions at all
    if int(q(f"SELECT count(*) AS n FROM {T}.fix_suggestions WHERE supplier_code = :code",
             code=code)["n"][0]) == 0 and latest_decisions(qlive, T, code).empty:
        return
    st.subheader("🔧 Suggested fixes")
    st.markdown("Most of your **delivery notes** don't say **which transport booking** they belong to, so the plant can't "
                "tell which truck carries which parts, and the truck stops at the gate. We found the right booking for "
                "many of them. **You decide**; approved links go to the plant's digital transport file. "
                "Your original messages are never changed.")
    with st.expander("ℹ️ What are these documents? (30 seconds)"):
        st.markdown(
            "Think of sending a big parcel with a courier:\n\n"
            "| Document | Like… | What it says |\n|---|---|---|\n"
            "| **Transport booking** (transport order, VDA 4933) | booking the courier pick-up | *\"Carrier, pick up my "
            "parts on 16 June at 08:00 and bring them to the plant, gate 4.\"* It has a **booking number**, e.g. 19000123. |\n"
            "| **Delivery note** (despatch advice, VDA 4987) | the packing list | *\"These parts and amounts are on the "
            "truck.\"* Sent to the plant when the truck leaves. |\n"
            "| **Transport status** (VDA 4945) | parcel tracking | *\"Truck B-XY 4711 is near Kassel… arrived.\"* |\n\n"
            "The packing list has a box for **the booking number**. Your system leaves it **empty**. We find the "
            "booking the way you match a receipt to your bank statement: **same supplier, same day, same parts and "
            "amounts** – and sometimes the truck itself confirms it.")

    # ---------------- data
    wlabel = st.radio("Match delivery notes to bookings picked up on the…", list(WINDOWS), horizontal=True,
                      key=f"window::{code}",
                      help="Measured on the hackathon data: almost all trucks are picked up on the despatch day, "
                           "a few one day later. 'Same day' gives fewer but more certain suggestions.")
    window = WINDOWS[wlabel]
    fx = q(f"""SELECT * FROM {T}.fix_suggestions WHERE supplier_code = :code AND date_window = :w
               ORDER BY despatch_date DESC""", code=code, w=window).drop_duplicates("message_key")
    dec = latest_decisions(qlive, T, code)
    bad = q(f"""SELECT msg_type, message_key, collect_set(rule_id) AS rules FROM {T}.findings
                WHERE supplier_code = :code AND responsible = 'supplier' AND category = 'matching'
                  AND severity IN ('error', 'warning') GROUP BY 1, 2""", code=code)
    pending = fx[~fx["message_key"].isin(set(dec["message_key"]))]
    green = pending[pending["confidence"] == "high"].reset_index(drop=True)
    yellow = pending[pending["confidence"] == "medium"].reset_index(drop=True)
    approved_keys = set(dec.loc[dec["decision"] == "approved", "message_key"])

    summary = st.container(border=True)
    labels = {"sure": f"🟢 Sure ({len(green)})", "check": f"🟡 To check ({len(yellow)})", "done": f"✅ Done ({len(dec)})"}
    view = st.radio("view", list(labels), format_func=labels.get, horizontal=True, key=f"view::{code}",
                    label_visibility="collapsed")
    selected_keys = set()

    # ---------------- 🟢 sure: tick and approve in one go
    if view == "sure":
        if green.empty:
            st.info("No open high-confidence suggestions." + (" Everything is decided – see ✅ Done." if len(dec) else ""))
        else:
            st.markdown("All parts of each delivery note are found in **exactly one** of your transport bookings. "
                        "Untick anything you are not sure about, then approve or reject the ticked rows.")
            st.caption(accuracy_note(q, T, window, "high"))
            table = pd.DataFrame({
                "✓": True,
                "delivery note": green["delivery_note"],
                "despatched": green["despatch_date"],
                "booking number now": green["current_value"].fillna("").replace("", "(empty)"),
                "→ suggested booking": green["suggested_value"],
                "why": green["reason"],
            })
            edited = st.data_editor(
                table, hide_index=True, use_container_width=True, key=f"green::{code}::{window}",
                height=min(36 * (len(table) + 1) + 4, 330), disabled=list(table.columns[1:]),
                column_config={"✓": st.column_config.CheckboxColumn(width="small"),
                               "why": st.column_config.TextColumn(width="large")})
            ticked = edited["✓"].to_numpy()
            selected_keys = set(green.loc[ticked, "message_key"])
            n = int(ticked.sum())
            c1, c2, _ = st.columns([2, 2, 3])
            if c1.button(f"✅ Approve {n}", type="primary", disabled=n == 0, use_container_width=True):
                log(execute, T, [row_for_log(green.iloc[i], "approved") for i in range(len(green)) if ticked[i]])
                st.toast(f"{n} fixes approved")
                st.rerun(scope="fragment")
            if c2.button(f"❌ Reject {n}", disabled=n == 0, use_container_width=True):
                log(execute, T, [row_for_log(green.iloc[i], "rejected") for i in range(len(green)) if ticked[i]])
                st.toast(f"{n} suggestions rejected")
                st.rerun(scope="fragment")
            with st.expander("🔍 Why this booking? Check any delivery note"):
                dn = st.selectbox("Delivery note", green["delivery_note"], key=f"insp::{code}")
                r = green[green["delivery_note"] == dn].iloc[0]
                evidence(q, T, r, r["suggested_value"])

    # ---------------- 🟡 to check: all shown cards decided at once
    if view == "check":
        if yellow.empty:
            st.info("Nothing to check – all suggestions for this company are certain (🟢), or already decided.")
        else:
            st.markdown("Several of your transport bookings could fit. Each card is pre-set to the **best match** – "
                        "open 🔍 Evidence, change what is wrong, then save all cards at once.")
            st.caption(accuracy_note(q, T, window, "medium") + " So please look at the evidence before saving.")
            page = yellow.head(PAGE)
            known = set(q(f"SELECT DISTINCT to_number FROM {T}.msg_4933 WHERE supplier_code = :code",
                          code=code)["to_number"].dropna().astype(str))
            choices, typed = {}, set()
            for _, r in page.iterrows():
                alts = [a.split(" ")[0] for a in (r["alternatives"] or "").split("; ") if a]
                options = ([r["suggested_value"]] + [a for a in alts if a != r["suggested_value"]]
                           + [OWN_OPT, REJECT_OPT, LATER_OPT])
                k = r["message_key"]
                with st.container(border=True):
                    st.markdown(f"**Delivery note {r['delivery_note']}** · despatched {r['despatch_date']} · "
                                f"order number now: `{r['current_value'] or 'empty'}`")
                    st.caption(r["reason"])
                    choice = st.radio("Belongs to booking", options, key=f"y::{k}", horizontal=True,
                                      captions=["best match"] + [""] * (len(options) - 1))
                    if choice == OWN_OPT:
                        choice = typed_value(f"yo::{k}", "Booking number (transport order)", "e.g. 19000123",
                                             known, r["delivery_note"], "delivery note number")
                        if choice != LATER_OPT:
                            typed.add(k)
                    elif choice not in (REJECT_OPT, LATER_OPT):
                        with st.expander(f"🔍 Why booking {choice}?"):
                            evidence(q, T, r, choice)
                    choices[k] = (r, choice)
            n_app = sum(c not in (REJECT_OPT, LATER_OPT) for _, c in choices.values())
            n_rej = sum(c == REJECT_OPT for _, c in choices.values())
            if st.button(f"💾 Save {n_app + n_rej} decisions ({n_app} approve · {n_rej} reject)", type="primary",
                         disabled=n_app + n_rej == 0):
                rows = [row_for_log(r, "rejected") if c == REJECT_OPT
                        else typed_row(row_for_log(r, "approved", c)) if k in typed
                        else row_for_log(r, "approved", c)
                        for k, (r, c) in choices.items() if c != LATER_OPT]
                log(execute, T, rows)
                st.toast(f"Saved {len(rows)} decisions")
                st.rerun(scope="fragment")
            if len(yellow) > PAGE:
                st.caption(f"Showing {PAGE} of {len(yellow)} – after saving, the next ones appear.")

    # ---------------- ✅ done: every decision with its own undo
    if view == "done":
        if dec.empty:
            st.info("No decisions yet. Approve or reject suggestions under 🟢 Sure and 🟡 To check.")
        else:
            approved = dec[dec["decision"] == "approved"]
            st.success(f"**{len(approved)} delivery notes are now linked to their transport booking** in the plant's "
                       "digital transport file – these trucks can be matched at the gate. "
                       f"({int((dec['decision'] == 'rejected').sum())} suggestions rejected.)")
            st.caption("Changed your mind? Undo puts the suggestion back.")
            hdr = st.columns([2, 2, 3, 3, 1.3])
            for h, t in zip(hdr, ["**Delivery note**", "**Decision**", "**Booking number**", "**By / when**", ""]):
                h.markdown(t)
            show = st.session_state.get(f"done_n::{code}", PAGE)
            for _, r in dec.head(show).iterrows():
                c = st.columns([2, 2, 3, 3, 1.3], vertical_alignment="center")
                c[0].write(r["delivery_note"])
                c[1].write("✅ approved" if r["decision"] == "approved" else "❌ rejected")
                c[2].write(f"{r['old_value'] or '(empty)'} → **{r['new_value']}**" if r["decision"] == "approved" else "unchanged")
                c[3].caption(f"{str(r['user_email']).split('@')[0]} · {pd.to_datetime(r['ts']):%d %b %H:%M}")
                # on_click: the undo is saved BEFORE the section redraws, so the row is gone at once
                # (with `if st.button(...): ... st.rerun()` the row stayed and further clicks were lost)
                c[4].button("↩ Undo", key=f"undo::{r['message_key']}", use_container_width=True,
                            on_click=_undo, args=(log, execute, T, {c_: r[c_] for c_ in LOG_COLS},
                                                  f"delivery note {r['delivery_note']}"))
            if len(dec) > show and st.button(f"Show more ({len(dec) - show} hidden)"):
                st.session_state[f"done_n::{code}"] = show + 4 * PAGE
                st.rerun(scope="fragment")

    # ---------------- prevention: note for the supplier's IT team
    with st.container(border=True):
        st.markdown("**🛠 Stop it at the source.** Fixing by hand only repairs the past. The real fix is one setting in "
                    "your system: fill in the booking number on every delivery note. Give this note to your IT / EDI team.")
        note = it_note(q, T, code, me, dec)
        c1, c2 = st.columns([1, 1])
        c1.download_button("⬇ Download note for your IT team", note, type="primary", use_container_width=True,
                           file_name=f"DQ_note_IT_{code}_{datetime.now(timezone.utc):%Y%m%d}.md", mime="text/markdown")
        if c2.toggle("Preview the note", key=f"itprev::{code}"):
            st.markdown(note)

    # ---------------- summary on top (computed last so it reflects the ticked rows)
    with summary:
        n_msgs = int(me["n_messages"])
        now = matching_score(bad, n_msgs, set())
        saved = matching_score(bad, n_msgs, approved_keys)
        after = matching_score(bad, n_msgs, approved_keys | selected_keys)
        c = st.columns(4)
        c[0].metric("🔗 Matching before any fix", f"{now:.0f}%")
        c[1].metric("with approved fixes", f"{saved:.0f}%", f"{saved - now:+.0f} pts")
        c[2].metric("+ ticked 🟢 rows", f"{after:.0f}%", f"{after - now:+.0f} pts")
        overall_after = (after + me["score_completeness"] + me["score_format"]) / 3
        c[3].metric("Overall score", f"{overall_after:.0f}", f"{overall_after - me['quality_score']:+.0f} vs {me['quality_score']:.0f}")


# ==================== carrier: fix truck statuses ====================

FIXABLE_CARRIER = {"TS_SHIPMENTNO_PLACEHOLDER"}
LOG_COLS_CARRIER = ["user_email", "carrier_code", "message_key", "suggestion_id", "rule_id",
                    "field_path", "old_value", "new_value", "confidence", "decision", "source"]


def latest_decisions_carrier(qlive, T, code):
    """Current decision per truck status (latest log row; 'undone' means pending again)."""
    return qlive(f"""
        SELECT * FROM (
          SELECT *, row_number() OVER (PARTITION BY message_key ORDER BY ts DESC) AS rn
          FROM {T}.fix_log_carrier WHERE carrier_code = :code)
        WHERE rn = 1 AND decision <> 'undone' ORDER BY ts DESC, message_key""", code=code)


def log_carrier(execute, T, rows):
    if not rows:
        return
    values, params = [], {}
    for i, r in enumerate(rows):
        values.append("(current_timestamp(), " + ", ".join(f":{c}_{i}" for c in LOG_COLS_CARRIER) + ")")
        params.update({f"{c}_{i}": "" if r.get(c) is None else str(r.get(c)) for c in LOG_COLS_CARRIER})
    execute(f"INSERT INTO {T}.fix_log_carrier (ts, {', '.join(LOG_COLS_CARRIER)}) VALUES {', '.join(values)}", params)


def row_for_log_carrier(r, decision, new_value=None):
    return {
        "user_email": current_user(), "carrier_code": r["carrier_code"], "message_key": r["message_key"],
        "suggestion_id": r["suggestion_id"], "rule_id": r["rule_id"], "field_path": r["field_path"],
        "old_value": r["current_value"],
        "new_value": new_value if new_value is not None else (r["suggested_value"] if decision == "approved" else ""),
        "confidence": r["confidence"], "decision": decision, "source": r["source"],
    }


LOG_COLS_MANUAL = ["user_email", "role", "company_code", "rule_id", "msg_type", "message_key",
                   "ref_number", "old_value", "new_value", "source"]


def log_manual(execute, T, rows):
    """Append manually noted corrections (rules without an automatic fix) to fix_log_manual."""
    if not rows:
        return
    values, params = [], {}
    for i, r in enumerate(rows):
        values.append("(current_timestamp(), " + ", ".join(f":{c}_{i}" for c in LOG_COLS_MANUAL) + ")")
        params.update({f"{c}_{i}": "" if r.get(c) is None else str(r.get(c)) for c in LOG_COLS_MANUAL})
    execute(f"INSERT INTO {T}.fix_log_manual (ts, {', '.join(LOG_COLS_MANUAL)}) VALUES {', '.join(values)}", params)


def matching_score_carrier(bad, n_messages, fixed_keys):
    """Matching score if the truck statuses in fixed_keys carried their (approved) delivery note number."""
    if not n_messages:
        return 0.0
    still_bad = sum(1 for r in bad.itertuples()
                    if not (r.msg_type == "4945" and r.message_key in fixed_keys and set(r.rules) <= FIXABLE_CARRIER))
    return round(100 * max(0, n_messages - still_bad) / n_messages, 1)


def carrier_note(q, T, code, me, dec):
    """Note for the carrier's dispatch / IT team: placeholder delivery note numbers in truck statuses."""
    counts = q(f"""SELECT f.rule_id, r.problem, r.field_path, r.fix, count(*) AS n
                   FROM {T}.findings f JOIN {T}.rules r USING (rule_id)
                   WHERE f.carrier_code = :c AND f.responsible = 'carrier' AND f.severity IN ('error', 'warning')
                   GROUP BY ALL ORDER BY n DESC""", c=code)
    n45 = int(me["n_4945"])
    ph = counts[counts["rule_id"] == "TS_SHIPMENTNO_PLACEHOLDER"]["n"].sum()
    ex = dec[dec["decision"] == "approved"].head(5)
    lines = [
        f"# Data quality note for the dispatch / IT team of {me['display_name']}",
        f"_Carrier code {code} · generated by the VDA Data Quality Cockpit on {datetime.now(timezone.utc):%d %b %Y} · "
        f"based on {n45} truck status messages (VDA 4945) sent to the plant._",
        "",
        "## Main issue: your statuses name the delivery with a placeholder",
        f"- **{int(ph)} of {n45} truck statuses** ({100 * ph / max(n45, 1):.0f} %) carry a placeholder instead of the "
        "real **delivery note number**.",
        "- **Field:** VDA 4945, `shipmentStatus/shipmentNumberAssignedByShipFrom/referenceNumber` – it must contain "
        "the supplier's delivery note (shipment) number, not a fixed text like 'LIEFERSCHEIN'.",
        "- **Why it matters:** the plant links your status to the truck and the delivery via this number. Without it the "
        "status cannot be matched, the gate time slot is wasted and unloading waits for a manual check.",
        "- **Likely cause:** your transport system writes a placeholder text into the shipment reference instead of "
        "the number that came with the transport order (VDA 4933).",
    ]
    if not ex.empty:
        lines += ["", "Correct numbers confirmed by your team in the cockpit:", "",
                  "| truck status | correct delivery note number |", "|---|---|"]
        lines += [f"| {r.message_key} | {r.new_value} |" for r in ex.itertuples()]
    other = counts[counts["rule_id"] != "TS_SHIPMENTNO_PLACEHOLDER"].head(5)
    if not other.empty:
        lines += ["", "## Other issues found in your messages", ""]
        lines += [f"- **{r.problem}** ({r.n}×) – field `{r.field_path}`. Fix: {r.fix}" for r in other.itertuples()]
    lines += ["", "## Checklist",
              "- [ ] Send the real delivery note number in referenceNumber of every truck status.",
              "- [ ] Send a test status for one transport order and check it shows up as linked in the cockpit.",
              "- [ ] Then re-check the remaining issues above."]
    return "\n".join(lines)


def fix_status(q, T, role, code):
    """Per rule: 'pending' suggestions still open in the cockpit and 'approved' decisions already taken."""
    if role == "Supplier":
        return q(f"""
            WITH dec AS (SELECT message_key, decision FROM (
                SELECT message_key, decision, row_number() OVER (PARTITION BY message_key ORDER BY ts DESC) AS rn
                FROM {T}.fix_log WHERE supplier_code = :code) WHERE rn = 1 AND decision <> 'undone')
            SELECT 'pending' AS kind, f.rule_id, count(DISTINCT s.message_key) AS n
            FROM {T}.fix_suggestions s
            JOIN {T}.findings f ON f.message_key = s.message_key AND f.supplier_code = :code
                 AND f.rule_id IN ('ASN_TO_MISSING', 'ASN_TO_IMPLAUSIBLE')
            LEFT JOIN dec d ON d.message_key = s.message_key
            WHERE s.supplier_code = :code AND d.message_key IS NULL
            GROUP BY 1, 2
            UNION ALL
            SELECT 'approved', f.rule_id, count(DISTINCT d.message_key)
            FROM dec d JOIN {T}.findings f ON f.message_key = d.message_key AND f.supplier_code = :code
                 AND f.rule_id IN ('ASN_TO_MISSING', 'ASN_TO_IMPLAUSIBLE')
            WHERE d.decision = 'approved' GROUP BY 1, 2""", code=code)
    return q(f"""
        WITH dec AS (SELECT message_key, rule_id, decision FROM (
            SELECT message_key, rule_id, decision, row_number() OVER (PARTITION BY message_key ORDER BY ts DESC) AS rn
            FROM {T}.fix_log_carrier WHERE carrier_code = :code) WHERE rn = 1 AND decision <> 'undone')
        SELECT 'pending' AS kind, s.rule_id, count(DISTINCT s.message_key) AS n
        FROM {T}.fix_suggestions_carrier s
        LEFT JOIN dec d ON d.message_key = s.message_key
        WHERE s.carrier_code = :code AND d.message_key IS NULL
        GROUP BY 1, 2
        UNION ALL
        SELECT 'approved', rule_id, count(DISTINCT message_key) FROM dec WHERE decision = 'approved' GROUP BY 1, 2""", code=code)


@st.fragment
def render_carrier(q, qlive, execute, T, code, me):
    """Carrier view of the detective: fix placeholder delivery note numbers in truck statuses."""
    # hide the whole section when this carrier has no suggestions and no decisions at all
    if int(q(f"SELECT count(*) AS n FROM {T}.fix_suggestions_carrier WHERE carrier_code = :code",
             code=code)["n"][0]) == 0 and latest_decisions_carrier(qlive, T, code).empty:
        return
    st.subheader("🔧 Suggested fixes")
    st.markdown(
        "Many of your **truck statuses** carry only a **placeholder** where the real **delivery note number** belongs "
        "(`shipmentNumberAssignedByShipFrom/referenceNumber`). Without that number the plant cannot link your status to "
        "the truck and the delivery, and the gate time slot is wasted. We matched most placeholders using your own "
        "messages – **you decide**; approved numbers go into the plant's digital transport file. "
        "Your original messages are never changed.")
    with st.expander("ℹ️ What is a truck status? (30 seconds)"):
        st.markdown(
            "Think of the tracking page of a parcel service:\n\n"
            "| Message | Like… | What it says |\n|---|---|---|\n"
            "| **Truck status** (VDA 4945) | one tracking event | *\"Truck B-XY 4711 left the supplier, is near Kassel, "
            "arrived at gate 4.\"* |\n"
            "| **Delivery note number** (VDA 4987, from the supplier) | the parcel number | the number the plant "
            "waits for |\n\n"
            "Every tracking event must say **which parcel (= delivery note) it belongs to**. Your system writes a "
            "placeholder text there instead of the number. We find the right number the way the plant does: your "
            "status names a **transport order**, and only **one delivery note** travels with it.")

    # ---------------- data
    fx = q(f"SELECT * FROM {T}.fix_suggestions_carrier WHERE carrier_code = :code ORDER BY geo_date DESC",
           code=code).drop_duplicates("message_key")
    dec = latest_decisions_carrier(qlive, T, code)
    bad = q(f"""SELECT msg_type, message_key, collect_set(rule_id) AS rules FROM {T}.findings
                WHERE carrier_code = :code AND responsible = 'carrier' AND category = 'matching'
                  AND severity IN ('error', 'warning') GROUP BY 1, 2""", code=code)
    pending = fx[~fx["message_key"].isin(set(dec["message_key"]))]
    green = pending[pending["confidence"] == "high"].reset_index(drop=True)
    yellow = pending[pending["confidence"] == "medium"].reset_index(drop=True)
    approved_keys = set(dec.loc[dec["decision"] == "approved", "message_key"])

    summary = st.container(border=True)
    labels = {"sure": f"🟢 Sure ({len(green)})", "check": f"🟡 To check ({len(yellow)})", "done": f"✅ Done ({len(dec)})"}
    view = st.radio("view", list(labels), format_func=labels.get, horizontal=True, key=f"view_c::{code}",
                    label_visibility="collapsed")
    selected_keys = set()

    # ---------------- 🟢 sure: tick and approve in one go
    if view == "sure":
        if green.empty:
            st.info("No open high-confidence suggestions." + (" Everything is decided – see ✅ Done." if len(dec) else ""))
        else:
            st.markdown("Each of these truck statuses can be linked to **exactly one** delivery note. "
                        "Untick anything you are not sure about, then approve or reject the ticked rows.")
            table = pd.DataFrame({
                "✓": True,
                "truck status": green["message_key"],
                "sent": green["geo_date"],
                "delivery note now": green["current_value"].fillna("").replace("", "(placeholder)"),
                "→ suggested delivery note": green["suggested_value"],
                "why": green["reason"],
            })
            edited = st.data_editor(
                table, hide_index=True, use_container_width=True, key=f"green_c::{code}",
                height=min(36 * (len(table) + 1) + 4, 330), disabled=list(table.columns[1:]),
                column_config={"✓": st.column_config.CheckboxColumn(),
                               "why": st.column_config.TextColumn(width="large")})
            ticked = edited["✓"].to_numpy()
            selected_keys = set(green.loc[ticked, "message_key"])
            n = int(ticked.sum())
            c1, c2, _ = st.columns([2, 2, 3])
            if c1.button(f"✅ Approve {n}", type="primary", disabled=n == 0, use_container_width=True):
                log_carrier(execute, T, [row_for_log_carrier(green.iloc[i], "approved")
                                         for i in range(len(green)) if ticked[i]])
                st.toast(f"{n} fixes approved")
                st.rerun(scope="fragment")
            if c2.button(f"❌ Reject {n}", disabled=n == 0, use_container_width=True):
                log_carrier(execute, T, [row_for_log_carrier(green.iloc[i], "rejected")
                                         for i in range(len(green)) if ticked[i]])
                st.toast(f"{n} suggestions rejected")
                st.rerun(scope="fragment")

    # ---------------- 🟡 to check: all shown cards decided at once
    if view == "check":
        if yellow.empty:
            st.info("Nothing to check – all suggestions for this company are certain (🟢), or already decided.")
        else:
            st.markdown("Several delivery notes could fit. Each card is pre-set to the **best match** – "
                        "check the reason, change what is wrong, then save all cards at once.")
            page = yellow.head(PAGE)
            known = set(q(f"SELECT DISTINCT shipment_number FROM {T}.msg_4987")["shipment_number"].dropna().astype(str))
            choices, typed = {}, set()
            for _, r in page.iterrows():
                alts = [a.split(" ")[0] for a in (r["alternatives"] or "").split("; ") if a]
                options = ([r["suggested_value"]] + [a for a in alts if a != r["suggested_value"]]
                           + [OWN_OPT, REJECT_OPT, LATER_OPT])
                k = r["message_key"]
                with st.container(border=True):
                    st.markdown(f"**Truck status {r['message_key']}** · sent {r['geo_date']} · transport order "
                                f"`{r['to_number']}` · delivery note now: `{r['current_value'] or 'placeholder'}`")
                    st.caption(r["reason"])
                    choice = st.radio("Correct delivery note", options, key=f"yc::{k}", horizontal=True,
                                      captions=["best match"] + [""] * (len(options) - 1))
                    if choice == OWN_OPT:
                        choice = typed_value(f"yco::{k}", "Delivery note number", "as printed on the delivery note",
                                             known, r["to_number"], "transport order number")
                        if choice != LATER_OPT:
                            typed.add(k)
                    choices[k] = (r, choice)
                    if choice not in (REJECT_OPT, LATER_OPT) and k not in typed:
                        with st.expander(f"🔍 Check status {k}"):
                            ev = q(f"""SELECT plate, geo_date AS day, to_number AS transport_order
                                       FROM {T}.msg_4945 WHERE carrier_code = :c AND document_id = :d
                                       ORDER BY day DESC LIMIT 5""", c=code, d=r["document_id"])
                            st.markdown(f"Statuses your trucks sent for **document {r['document_id']}** "
                                        "(same transport order):")
                            st.dataframe(ev, hide_index=True, use_container_width=True)
            n_app = sum(c not in (REJECT_OPT, LATER_OPT) for _, c in choices.values())
            n_rej = sum(c == REJECT_OPT for _, c in choices.values())
            if st.button(f"💾 Save {n_app + n_rej} decisions ({n_app} approve · {n_rej} reject)", type="primary",
                         disabled=n_app + n_rej == 0):
                rows = [row_for_log_carrier(r, "rejected") if c == REJECT_OPT
                        else typed_row(row_for_log_carrier(r, "approved", c)) if k in typed
                        else row_for_log_carrier(r, "approved", c)
                        for k, (r, c) in choices.items() if c != LATER_OPT]
                log_carrier(execute, T, rows)
                st.toast(f"Saved {len(rows)} decisions")
                st.rerun(scope="fragment")
            if len(yellow) > PAGE:
                st.caption(f"Showing {PAGE} of {len(yellow)} – after saving, the next ones appear.")

    # ---------------- ✅ done: every decision with its own undo
    if view == "done":
        if dec.empty:
            st.info("No decisions yet. Approve or reject suggestions under 🟢 Sure and 🟡 To check.")
        else:
            approved = dec[dec["decision"] == "approved"]
            st.success(f"**{len(approved)} truck statuses now name their delivery note** in the plant's digital "
                       "transport file – these statuses can be matched at the gate. "
                       f"({int((dec['decision'] == 'rejected').sum())} suggestions rejected.)")
            st.caption("Changed your mind? Undo puts the suggestion back.")
            hdr = st.columns([2, 2, 3, 3, 1.3])
            for h, t in zip(hdr, ["**Truck status**", "**Decision**", "**Delivery note**", "**By / when**", ""]):
                h.markdown(t)
            show = st.session_state.get(f"done_c::{code}", PAGE)
            for _, r in dec.head(show).iterrows():
                c = st.columns([2, 2, 3, 3, 1.3], vertical_alignment="center")
                c[0].write(r["message_key"])
                c[1].write("✅ approved" if r["decision"] == "approved" else "❌ rejected")
                c[2].write(f"{r['old_value'] or '(placeholder)'} → **{r['new_value']}**" if r["decision"] == "approved" else "unchanged")
                c[3].caption(f"{str(r['user_email']).split('@')[0]} · {pd.to_datetime(r['ts']):%d %b %H:%M}")
                c[4].button("↩ Undo", key=f"undo_c::{r['message_key']}", use_container_width=True,
                            on_click=_undo, args=(log_carrier, execute, T, {c_: r[c_] for c_ in LOG_COLS_CARRIER},
                                                  f"truck status {r['message_key']}"))
            if len(dec) > show and st.button(f"Show more ({len(dec) - show} hidden)"):
                st.session_state[f"done_c::{code}"] = show + 4 * PAGE
                st.rerun(scope="fragment")

    # ---------------- prevention: note for the carrier's dispatch / IT team
    with st.container(border=True):
        st.markdown("**🛠 Stop it at the source.** Fixing by hand only repairs the past. The real fix is one "
                    "setting in your system: send the real delivery note number in every truck status. "
                    "Give this note to your dispatch / IT team.")
        note = carrier_note(q, T, code, me, dec)
        c1, c2 = st.columns([1, 1])
        c1.download_button("⬇ Download note for your dispatch / IT team", note, type="primary",
                           use_container_width=True,
                           file_name=f"DQ_note_IT_carrier_{code}_{datetime.now(timezone.utc):%Y%m%d}.md",
                           mime="text/markdown")
        if c2.toggle("Preview the note", key=f"itprev_c::{code}"):
            st.markdown(note)

    # ---------------- summary on top (computed last so it reflects the ticked rows)
    with summary:
        n_msgs = int(me["n_messages"])
        now = matching_score_carrier(bad, n_msgs, set())
        saved = matching_score_carrier(bad, n_msgs, approved_keys)
        after = matching_score_carrier(bad, n_msgs, approved_keys | selected_keys)
        c = st.columns(4)
        c[0].metric("🔗 Matching before any fix", f"{now:.0f}%")
        c[1].metric("with approved fixes", f"{saved:.0f}%", f"{saved - now:+.0f} pts")
        c[2].metric("+ ticked 🟢 rows", f"{after:.0f}%", f"{after - now:+.0f} pts")
        overall_after = (after + me["score_completeness"] + me["score_format"]) / 3
        c[3].metric("Overall score", f"{overall_after:.0f}", f"{overall_after - me['quality_score']:+.0f} vs {me['quality_score']:.0f}")
